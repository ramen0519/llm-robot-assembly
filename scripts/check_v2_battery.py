"""Read-only audit/import of the actual Framework source; no invented export proof."""
from pathlib import Path
import argparse
import shutil
import numpy as np
from assembly_v12.contracts import read,write,sha,relative
from assembly_v2.geometry import load_mesh,geometry_matches,prepare_asset
from assembly_v2.preparation import PROFILE
from assembly_v2.budget import Budget

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--input',required=True);ap.add_argument('--output',required=True)
    a=ap.parse_args();source=Path(a.input).absolute();out=Path(a.output).absolute();out.mkdir(parents=True,exist_ok=False)
    budget=Budget(300);transfer=read(source/'transfer.json');raw=read(source/'source/worker_result.json')
    result={'product':'actual_framework_battery','api_calls':0,'robot_assembly':'not_run','assets':{}}
    try:
        for name,checksum in transfer['bundle_sha256'].items():
            if sha(relative(source,name))!=checksum:raise ValueError('Transferred source changed: '+name)
        chain=raw['selected_plan'];remaining=set(transfer['parts']);order=[]
        for step in chain:
            moving=step['part_move'];info=step['sim_info']
            if set(step['parent'])!=remaining or info.get('feasible') is not True or info.get('base_part')!=transfer['fixed_base'] or info.get('parts_fix'):
                raise ValueError('No continuous selected chain with only the fixed base.')
            if moving not in remaining or set(step['child'])!=remaining-{moving}:raise ValueError('Invalid selected transition.')
            order.append(moving);remaining=set(step['child'])
        if remaining!={transfer['fixed_base']} or order!=transfer['disassembly_order']:raise ValueError('Final remainder/order mismatch.')
        if not raw.get('actual_physics') or not raw.get('success'):raise ValueError('Not an actual native success.')
        result.update(selected_chain='verified',disassembly_order=order,assembly_candidate=list(reversed(order)),final_remaining=sorted(remaining),
            upstream_scope='Astra ranking + native ASAP/RedMax part-level disassembly; no robot-trajectory equivalence',
            modern_export_status='not_available: dense native trajectory/check/media bundle must be regenerated by the bridge')
        shutil.copytree(source/'source',out/'source');shutil.copy2(source/'transfer.json',out/'legacy_transfer.json')
        product=out/'product';product.mkdir();items=[]
        for pid,row in transfer['parts'].items():
            budget.check('battery_source_geometry');local=load_mesh(source/row['local_mesh']);placed=local.copy()
            t=np.eye(4);t[:3,:3]=row['assembled_body_rotation_product'];t[:3,3]=row['assembled_body_position_product_m']
            placed.apply_transform(t)
            original=load_mesh(source/row['source_obj'],transfer['coordinates']['metres_per_source_unit'])
            if not geometry_matches(placed,original):raise ValueError('Source unit/embedded placement contradicts local CAD: '+pid)
            dest=product/(pid+'.obj');shutil.copy2(source/row['local_mesh'],dest);mm=t.copy();mm[:3,3]*=1000
            items.append({'part_id':pid,'mesh':dest.name,'assembly_matrix_mm':mm.tolist(),'mesh_coordinate_frame':'part_local'})
        write(product/'product.json',{'schema':'development_goal_CAD/v1','unit':'m','fixed_base':transfer['fixed_base'],'parts':items,
              'provenance':'Actual Framework CAD; source/legacy_transfer.json retains original STEP unit normalization and selected proof.'})
        result['source_geometry']='passed';result['source_product_input']=str(product/'product.json')
        # Prioritize the actual first installation and base. Every failed quality
        # result is retained; no simplified box is substituted for this product.
        for pid in [order[-1],transfer['fixed_base'],*[p for p in transfer['parts'] if p not in (order[-1],transfer['fixed_base'])]]:
            try:
                asset=prepare_asset(product/(pid+'.obj'),out/'assets'/pid,read(PROFILE),budget)
                result['assets'][pid]={'status':'passed','algorithm':asset['algorithm'],'hulls':len(asset['hulls']),'quality':asset['quality']}
            except Exception as exc:result['assets'][pid]={'status':'failed','reason':str(exc)}
            write(out/'battery_check.json',result)
        result['status']='source_audited_collision_attempted'
    except Exception as exc:result.update(status='failed',error=type(exc).__name__+': '+str(exc))
    write(out/'battery_check.json',result);print(out/'battery_check.json',flush=True)

if __name__=='__main__':main()
